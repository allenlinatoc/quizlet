"""Browser smoke test. Run through webapp-testing's with_server.py helper."""
from pathlib import Path
from tempfile import TemporaryDirectory
import os
import subprocess
from playwright.sync_api import sync_playwright, expect

BASE = os.environ["QUIZLET_TEST_BASE"]

with sync_playwright() as playwright:
    chrome = os.environ.get("QUIZLET_CHROME_PATH")
    default_chrome = Path(r"C:\Program Files\Google\Chrome\Application\chrome.exe")
    if not chrome and default_chrome.exists():
        chrome = str(default_chrome)
    browser = playwright.chromium.launch(headless=True, **({"executable_path": chrome} if chrome else {}))
    page = browser.new_page(viewport={"width": 1280, "height": 800})
    errors = []
    page.on("pageerror", lambda error: errors.append(str(error)))
    try:
        page.goto(BASE, wait_until="networkidle")
        expect(page.get_by_role("heading", name="A little progress every day.")).to_be_visible()
        page.get_by_label("Theme").select_option("dark")
        expect(page.locator("html")).to_have_attribute("data-theme", "dark")
        page.reload(wait_until="networkidle")
        expect(page.get_by_label("Theme")).to_have_value("dark")
        page.get_by_role("button", name="Create from PDF").click()
        expect(page.get_by_role("heading", name="Create from PDF")).to_be_visible()
        Path(".tools/ui-review").mkdir(parents=True, exist_ok=True)
        page.screenshot(path=".tools/ui-review/pdf-dark.png", full_page=True)
        with TemporaryDirectory(prefix="quizlet-pdf-browser-") as temp:
            pdf_path = Path(temp) / "lesson.pdf"
            subprocess.run(["node", "--input-type=module", "-e", "import {PDFDocument} from 'pdf-lib'; import {writeFileSync} from 'node:fs'; const d=await PDFDocument.create(); d.addPage(); writeFileSync(process.argv[1],await d.save());", str(pdf_path)], check=True)
            page.locator('input[type="file"][accept*="pdf"]').set_input_files(str(pdf_path))
            expect(page.get_by_text("1 pages · new")).to_be_visible()
            expect(page.locator("canvas.pdf-canvas")).to_be_visible()
            page.get_by_role("button", name="Save settings and estimate").click()
            expect(page.get_by_text("Estimated reservation", exact=False)).to_be_visible()
            page.get_by_role("button", name="All conversions").click()
            expect(page.get_by_role("button", name="lesson · new · 0 questions")).to_be_visible()
            page.locator('input[type="file"][accept*="pdf"]').set_input_files(str(pdf_path))
            page.get_by_label("Processing provider").select_option("text-extract")
            expect(page.get_by_label("Budget (USD)")).to_have_count(0)
            page.get_by_role("button", name="Save settings", exact=True).click()
            expect(page.get_by_text("Local extraction is configured", exact=False)).to_be_visible()
            expect(page.get_by_text("Selected pages are sent to the configured extraction service", exact=False)).to_be_visible()
        page.get_by_role("button", name="Back to library").click()
        with TemporaryDirectory(prefix="quizlet-excel-browser-") as temp:
            workbook_path = Path(temp) / "questions.xlsx"
            js = "const ExcelJS=require('exceljs'); (async()=>{const w=new ExcelJS.Workbook();const s=w.addWorksheet('Questions');s.addRow(['type','prompt','choice_a','choice_b','choice_c','choice_d','choice_e','choice_f','correct_answers','explanation']);s.addRow([process.argv[2],'Excel question','Yes','No','','','','','A','Example']);await w.xlsx.writeFile(process.argv[1]);})()"
            subprocess.run(["node", "-e", js, str(workbook_path), "invalid"], check=True)
            page.get_by_role("button", name="Import Excel").click()
            page.screenshot(path=".tools/ui-review/excel-dark.png", full_page=True)
            with page.expect_download() as template:
                page.get_by_role("link", name="Download Excel template").click()
            assert template.value.suggested_filename.endswith(".xlsx")
            page.get_by_label("Excel file (.xlsx)").set_input_files(str(workbook_path))
            expect(page.get_by_text("Use single, multiple or boolean", exact=False)).to_be_visible()
            subprocess.run(["node", "-e", js, str(workbook_path), "single"], check=True)
            page.get_by_label("Excel file (.xlsx)").set_input_files(str(workbook_path))
            expect(page.get_by_text("1 valid question(s)", exact=False)).to_be_visible()
            page.get_by_role("button", name="Import 1 questions").click()
            expect(page.get_by_role("dialog", name="Import Excel questions")).to_have_count(0)
            expect(page.get_by_role("heading", name="questions", exact=True)).to_be_visible()
            expect(page.get_by_text("Excel question", exact=True)).to_be_visible()
            page.get_by_role("button", name="Import Excel").click()
            page.get_by_label("Excel file (.xlsx)").set_input_files(str(workbook_path))
            expect(page.get_by_text("1 valid question(s)", exact=False)).to_be_visible()
            page.get_by_role("button", name="Import 1 questions").click()
            expect(page.get_by_role("dialog", name="Import Excel questions")).to_have_count(0)
            expect(page.get_by_text("Excel question", exact=True)).to_have_count(2)
            page.get_by_role("button", name="All decks").click()
        page.once("dialog", lambda dialog: dialog.accept("Biology"))
        page.get_by_role("button", name="Create a deck", exact=True).click()
        expect(page.get_by_role("heading", name="Biology")).to_be_visible()
        page.get_by_role("button", name="Add a question").click()
        editors = page.locator(".tiptap")
        expect(editors).to_have_count(4)
        page.screenshot(path=".tools/ui-review/editor-dark.png", full_page=True)
        editors.nth(0).fill("What makes leaves green?")
        def formula_dialog(dialog):
            dialog.accept("x^2") if dialog.type == "prompt" else dialog.dismiss()
        page.on("dialog", formula_dialog)
        page.locator(".rich-editor").first.get_by_role("button", name="Add formula").click()
        page.remove_listener("dialog", formula_dialog)
        expect(page.locator(".formula-preview").first).to_be_visible()
        editors.nth(1).fill("Chlorophyll")
        editors.nth(2).fill("Oxygen")
        editors.nth(3).fill("Chlorophyll absorbs light.")
        page.get_by_role("button", name="Mark choice 1 correct").click()
        page.get_by_role("button", name="Save question").click()
        expect(page.get_by_role("heading", name="Biology")).to_be_visible()
        expect(page.get_by_text("What makes leaves green?")).to_be_visible()
        page.get_by_role("button", name="Settings", exact=True).click()
        page.get_by_label("Choice order").select_option("random")
        expect(page.get_by_label("Choice order")).to_have_value("random")
        page.reload(wait_until="networkidle")
        expect(page.get_by_text("What makes leaves green?")).to_be_visible()
        page.get_by_role("button", name="Start practicing").click()
        page.get_by_role("button", name="Chlorophyll").click()
        page.get_by_role("button", name="Submit answer").click()
        expect(page.get_by_text("That’s correct!")).to_be_visible()
        page.locator(".play-card").get_by_role("button", name="Finish session", exact=True).click()
        expect(page.get_by_text("100%")).to_be_visible()
        expect(page.get_by_text("Chlorophyll absorbs light.")).to_be_visible()
        page.screenshot(path=".tools/ui-review/result-dark.png", full_page=True)
        page.get_by_role("button", name="View Study History").click()
        expect(page.get_by_label("Quiz Deck")).not_to_have_value("")
        expect(page.locator(".history-row")).to_have_count(1)
        page.get_by_role("button", name="View result for Biology").first.click()
        page.get_by_role("button", name="Back to History list").last.click()
        expect(page.get_by_label("Quiz Deck")).not_to_have_value("")
        page.get_by_role("button", name="View Quiz Deck").click()
        with TemporaryDirectory(prefix="quizlet-browser-") as temp:
            with page.expect_download() as download_info:
                page.get_by_role("link", name="Export").click()
            exported = Path(temp) / "deck.zip"
            download_info.value.save_as(exported)
            page.get_by_role("button", name="All decks").click()
            with page.expect_file_chooser() as chooser:
                page.get_by_role("button", name="Import QTI").click()
            chooser.value.set_files(str(exported))
            expect(page.get_by_role("heading", name="Biology")).to_be_visible()
            expect(page.get_by_text("What makes leaves green?")).to_be_visible()
        page.get_by_role("button", name="Add question", exact=True).click()
        editors = page.locator(".tiptap")
        expect(editors).to_have_count(4)
        editors.nth(0).fill("What do roots absorb?")
        editors.nth(1).fill("Water")
        editors.nth(2).fill("Sunlight")
        page.get_by_role("button", name="Mark choice 1 correct").click()
        page.get_by_role("button", name="Save question").click()
        expect(page.get_by_role("heading", name="Biology")).to_be_visible()
        page.get_by_role("button", name="Start practicing").click()
        page.get_by_role("button", name="Skip", exact=True).click()
        expect(page.get_by_text("What do roots absorb?")).to_be_visible()
        choice_order = page.locator(".answer-option").all_text_contents()
        page.get_by_role("button", name="Save and exit").click()
        page.get_by_role("button", name="Resume session").click()
        expect(page.get_by_text("What do roots absorb?")).to_be_visible()
        assert page.locator(".answer-option").all_text_contents() == choice_order
        page.once("dialog", lambda dialog: dialog.accept())
        page.get_by_role("button", name="Finish session", exact=True).click()
        expect(page.get_by_text("0%")).to_be_visible()
        page.set_viewport_size({"width": 390, "height": 844})
        expect(page.get_by_role("button", name="Open navigation")).to_be_visible()
        page.get_by_role("button", name="Open navigation").click()
        page.get_by_role("navigation").get_by_role("button", name="Study history").click()
        expect(page.get_by_role("heading", name="Study history")).to_be_visible()
        page.screenshot(path=".tools/ui-review/history-mobile-dark.png", full_page=True, animations="disabled")
        expect(page.get_by_label("Theme")).to_be_visible()
        expect(page.locator(".history-row")).to_have_count(2)
        page.get_by_label("Score", exact=True).select_option("high")
        expect(page.locator(".history-row")).to_have_count(1)
        page.go_back(wait_until="networkidle")
        expect(page.get_by_label("Score", exact=True)).to_have_value("all")
        page.go_forward(wait_until="networkidle")
        expect(page.get_by_label("Score", exact=True)).to_have_value("high")
        page.reload(wait_until="networkidle")
        expect(page.get_by_label("Score", exact=True)).to_have_value("high")
        page.get_by_role("button", name="View result for Biology").first.click()
        expect(page.get_by_role("button", name="View Study History")).to_be_visible()
        page.get_by_role("button", name="Back to History list").first.click()
        expect(page.get_by_label("Quiz Deck")).not_to_have_value("")
        expect(page.get_by_label("Score", exact=True)).to_have_value("high")
        page.once("dialog", lambda dialog: dialog.dismiss())
        page.get_by_role("button", name="Delete history for Biology").click()
        expect(page.locator(".history-row")).to_have_count(1)
        page.once("dialog", lambda dialog: dialog.accept())
        page.get_by_role("button", name="Delete history for Biology").click()
        expect(page.get_by_role("heading", name="No matching study history")).to_be_visible()
        expect(page.get_by_label("Score", exact=True)).to_have_value("high")
        page.get_by_label("Theme").select_option("light")
        expect(page.locator("html")).to_have_attribute("data-theme", "light")
        page.screenshot(path=".tools/ui-review/history-mobile-light.png", full_page=True)
        page.get_by_role("button", name="Clear filters").first.click()
        page.get_by_role("button", name="View result for Biology").first.click()
        saved_result_url = page.url
        page.get_by_role("button", name="View Quiz Deck").click()
        page.once("dialog", lambda dialog: dialog.accept())
        page.get_by_role("button", name="Delete deck").click()
        page.goto(saved_result_url, wait_until="networkidle")
        expect(page.get_by_role("heading", name="Look at you go.")).to_be_visible()
        expect(page.get_by_role("button", name="View Quiz Deck")).to_have_count(0)
        page.get_by_role("button", name="View Study History").click()
        expect(page.get_by_label("Quiz Deck")).not_to_have_value("")
        expect(page.get_by_text("Deleted deck", exact=True)).to_be_visible()
        assert not errors, f"Browser errors: {errors}"
        print("Browser smoke test passed")
    except Exception:
        Path(".tools").mkdir(exist_ok=True)
        page.screenshot(path=".tools/browser-failure.png", full_page=True)
        print("Browser errors:", errors)
        raise
    finally:
        browser.close()
